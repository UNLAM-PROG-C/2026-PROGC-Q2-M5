# --- acentos (se componen) --------------------------------------------------
_ACUTE = ("..#", ".#.")
_TILDE = (".#.#", "#.#.")
_DIAER = ("#.#",)


def _compose(base, mark, lower):
    top, rows = G[base]
    w, mw = len(rows[0]), len(mark[0])
    off = (w - mw) // 2
    mrow = 2 if lower else 0
    grid = set()
    for r, line in enumerate(rows):
        for c, ch in enumerate(line):
            if ch == "#":
                grid.add((top + r, c))
    for r, line in enumerate(mark):
        for c, ch in enumerate(line):
            if ch == "#":
                grid.add((mrow + r, off + c))
    c0 = min(c for _, c in grid)
    c1 = max(c for _, c in grid) + 1
    new_top = min(top, mrow)
    rows_out = tuple("".join("#" if (r, c) in grid else "." for c in range(c0, c1))
                     for r in range(new_top, top + len(rows)))
    return new_top, rows_out


for _src, _dst in (("A", "Á"), ("E", "É"), ("I", "Í"), ("O", "Ó"), ("U", "Ú")):
    G[_dst] = _compose(_src, _ACUTE, False)
G["Ñ"] = _compose("N", _TILDE, False)
G["Ü"] = _compose("U", _DIAER, False)
for _src, _dst in (("a", "á"), ("e", "é"), ("ı", "í"), ("o", "ó"), ("u", "ú")):
    G[_dst] = _compose(_src, _ACUTE, True)
G["ñ"] = _compose("n", _TILDE, True)
G["ü"] = _compose("u", _DIAER, True)

REPLACE = {"…": "...", "·": "-", "—": "-", "–": "-", "−": "-", "º": "o", "ª": "a"}


def normalize(text):
    for a, b in REPLACE.items():
        text = text.replace(a, b)
    return "".join(c if c in G else ("?" if c.strip() else " ") for c in text)


def text_width(text, scale=1):
    text = normalize(text)
    if not text:
        return 0
    w = sum(len(G[c][1][0]) + 1 for c in text) - 1
    return w * scale


def _mask(text):
    """Superficie blanca (escala 1) con los píxeles del texto."""
    text = normalize(text)
    w = max(1, text_width(text))
    surf = pygame.Surface((w, BOX_H), pygame.SRCALPHA)
    x = 0
    for c in text:
        top, rows = G[c]
        for r, line in enumerate(rows):
            for cx, ch in enumerate(line):
                if ch == "#":
                    surf.set_at((x + cx, top + r), (255, 255, 255, 255))
        x += len(rows[0]) + 1
    return surf


_cache = {}


def render(text, scale=2, color=(255, 255, 255), outline=None, shadow=None, shadow_off=1):
    """Texto nítido. outline: color del contorno (1 píxel de la fuente);
    shadow: color de sombra desplazada hacia abajo-derecha."""
    key = (text, scale, tuple(color), tuple(outline) if outline else None,
           tuple(shadow) if shadow else None, shadow_off)
    s = _cache.get(key)
    if s is not None:
        return s
    m = _mask(text)
    w, h = m.get_size()
    pad = 1 if outline else 0
    extra = shadow_off if shadow else 0
    base = pygame.Surface((w + 2 * pad + extra, h + 2 * pad + extra), pygame.SRCALPHA)

    def tinted(col):
        t = m.copy()
        t.fill((*col[:3], 255), special_flags=pygame.BLEND_RGBA_MULT)
        return t
    if shadow:
        sh = tinted(shadow)
        if outline:
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    base.blit(sh, (pad + dx + extra, pad + dy + extra))
        else:
            base.blit(sh, (extra, extra))
    if outline:
        ol = tinted(outline)
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                if dx or dy:
                    base.blit(ol, (pad + dx, pad + dy))
    base.blit(tinted(color), (pad, pad))
    s = pygame.transform.scale(base, (base.get_width() * scale, base.get_height() * scale))
    if len(_cache) > 800:
        _cache.clear()
    _cache[key] = s
    return s


def render_led(text, dot=4, on=(255, 196, 70), off=(58, 54, 50), bg=None):
    """Texto de tablero: cada píxel de la fuente es una lámpara cuadrada."""
    key = ("led", text, dot, tuple(on), tuple(off) if off else None, tuple(bg) if bg else None)
    s = _cache.get(key)
    if s is not None:
        return s
    m = _mask(text)
    w, _ = m.get_size()
    top, bottom = 2, 9          # sólo la franja de mayúsculas y dígitos
    s = pygame.Surface((w * dot + 1, (bottom - top) * dot + 1), pygame.SRCALPHA)
    if bg:
        s.fill(bg)
    hi = tuple(min(255, c + 70) for c in on)
    size = max(1, dot - 1)
    for y in range(top, bottom):
        for x in range(w):
            r = pygame.Rect(x * dot + 1, (y - top) * dot + 1, size, size)
            if m.get_at((x, y)).a > 0:
                pygame.draw.rect(s, on, r)
                if size >= 3:
                    pygame.draw.rect(s, hi, (r.x, r.y, size - 1, 1))
            elif off:
                pygame.draw.rect(s, off, r)
    _cache[key] = s
    return s
